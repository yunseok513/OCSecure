-- OCS-LITE: take the module away from one business schema (run as SYS)
-- Usage:  @41_disconnect_app.sql <app_schema>

SET VERIFY OFF
DEFINE app = '&1'

DROP SYNONYM &app..LITE_ENC;
DROP SYNONYM &app..LITE_DEC;
DROP SYNONYM &app..LITE_MASK;
DROP SYNONYM &app..LITE_PWD_HASH;
DROP SYNONYM &app..LITE_PWD_VERIFY;
DROP SYNONYM &app..LITE_READY;

REVOKE EXECUTE ON LITE_OWNER.LITE_ENC        FROM &app;
REVOKE EXECUTE ON LITE_OWNER.LITE_DEC        FROM &app;
REVOKE EXECUTE ON LITE_OWNER.LITE_MASK       FROM &app;
REVOKE EXECUTE ON LITE_OWNER.LITE_PWD_HASH   FROM &app;
REVOKE EXECUTE ON LITE_OWNER.LITE_PWD_VERIFY FROM &app;
REVOKE EXECUTE ON LITE_OWNER.LITE_READY      FROM &app;
