-- OCS-LITE: 업무 스키마 하나에서 모듈 사용 권한을 회수합니다 (SYS 로 접속).
-- 사용법:  @41_disconnect_app.sql <업무 스키마>

SET VERIFY OFF
DEFINE app = '&1'

DROP SYNONYM &app..FN_SFC_ENC;
DROP SYNONYM &app..FN_SFC_DEC;
DROP SYNONYM &app..FN_SFC_MASK;
DROP SYNONYM &app..FN_SFC_PWD_HASH;
DROP SYNONYM &app..FN_SFC_PWD_VERIFY;
DROP SYNONYM &app..FN_SFC_READY;

REVOKE EXECUTE ON SFC_OWNER.FN_SFC_ENC        FROM &app;
REVOKE EXECUTE ON SFC_OWNER.FN_SFC_DEC        FROM &app;
REVOKE EXECUTE ON SFC_OWNER.FN_SFC_MASK       FROM &app;
REVOKE EXECUTE ON SFC_OWNER.FN_SFC_PWD_HASH   FROM &app;
REVOKE EXECUTE ON SFC_OWNER.FN_SFC_PWD_VERIFY FROM &app;
REVOKE EXECUTE ON SFC_OWNER.FN_SFC_READY      FROM &app;
