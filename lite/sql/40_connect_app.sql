-- OCS-LITE 7단계 (SYS 로 접속): 업무 스키마 하나가 모듈을 쓸 수 있게 합니다.
--
-- 사용법:  @40_connect_app.sql <업무 스키마>
--
-- 업무 스키마는 FN_SFC_* 함수의 실행 권한과 함수마다 시노님을 받습니다. 그래서
-- 쿼리에서 접두어 없이 FN_SFC_ENC(컬럼) 처럼 쓸 수 있습니다. 그 밖의 권한은 주지
-- 않습니다. SFC_KEY, PKG_SFC, SFC_SEAL 에는 접근하지 못합니다.
-- 연결을 끊으려면 41_disconnect_app.sql 을 실행합니다.

WHENEVER SQLERROR EXIT FAILURE
SET VERIFY OFF
DEFINE app = '&1'

GRANT EXECUTE ON SFC_OWNER.FN_SFC_ENC        TO &app;
GRANT EXECUTE ON SFC_OWNER.FN_SFC_DEC        TO &app;
GRANT EXECUTE ON SFC_OWNER.FN_SFC_MASK       TO &app;
GRANT EXECUTE ON SFC_OWNER.FN_SFC_PWD_HASH   TO &app;
GRANT EXECUTE ON SFC_OWNER.FN_SFC_PWD_VERIFY TO &app;
GRANT EXECUTE ON SFC_OWNER.FN_SFC_READY      TO &app;

CREATE OR REPLACE SYNONYM &app..FN_SFC_ENC        FOR SFC_OWNER.FN_SFC_ENC;
CREATE OR REPLACE SYNONYM &app..FN_SFC_DEC        FOR SFC_OWNER.FN_SFC_DEC;
CREATE OR REPLACE SYNONYM &app..FN_SFC_MASK       FOR SFC_OWNER.FN_SFC_MASK;
CREATE OR REPLACE SYNONYM &app..FN_SFC_PWD_HASH   FOR SFC_OWNER.FN_SFC_PWD_HASH;
CREATE OR REPLACE SYNONYM &app..FN_SFC_PWD_VERIFY FOR SFC_OWNER.FN_SFC_PWD_VERIFY;
CREATE OR REPLACE SYNONYM &app..FN_SFC_READY      FOR SFC_OWNER.FN_SFC_READY;

PROMPT
PROMPT Done. Check as the business schema:  SELECT FN_SFC_READY FROM DUAL;
